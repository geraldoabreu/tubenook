/**
 * Translate a key for the given language ('pt-BR' | 'pt-PT' | 'en' | 'es') with optional `{param}` interpolation.
 * @param {string} key
 * @param {'pt-BR' | 'pt-PT' | 'en' | 'es'} [lang='pt-BR']
 * @param {Record<string, string | number>} [params]
 * @returns {string}
 */
export function t(key, lang = 'pt-BR', params = undefined) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['pt-BR'];
  let text = dict[key] ?? TRANSLATIONS.en[key];
  if (text === undefined && typeof key === 'string' && !key.includes('.')) {
    const suffix = `.${key}`;
    const matchedKey = Object.keys(dict).find((k) => k.endsWith(suffix));
    if (matchedKey) text = dict[matchedKey];
  }
  if (text === undefined) text = key;
  if (params && typeof params === 'object') {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/**
 * Detect default language from browser/environment, recognizing 'pt-BR', 'pt-PT' (or 'pt'), 'es', and 'en'.
 * Defaults to 'pt-BR' when navigator.language is unavailable.
 * @returns {'pt-BR' | 'pt-PT' | 'en' | 'es'}
 */
export function detectDefaultLanguage() {
  if (typeof navigator !== 'undefined' && navigator.language) {
    const raw = navigator.language.toLowerCase().trim();
    if (raw === 'pt-br' || raw.startsWith('pt-br') || raw.startsWith('pt_br')) {
      return 'pt-BR';
    }
    if (raw === 'pt-pt' || raw === 'pt' || raw.startsWith('pt-') || raw.startsWith('pt_')) {
      return 'pt-PT';
    }
    if (raw === 'es' || raw.startsWith('es-') || raw.startsWith('es_')) {
      return 'es';
    }
    return 'en';
  }
  return 'pt-BR';
}
